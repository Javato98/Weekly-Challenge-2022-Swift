func strInversion(str : String) -> String { 
    var str_inverse = ""
    for i in stride(from: str.count - 1, through: 0, by: -1) {
        let index =  str.index(str.startIndex, offsetBy: i)
        str_inverse += String(str[index])
    }
    return str_inverse
}

